// decodes the utf-8 character at *text, moving *text past it.
// a malformed sequence decodes as U+FFFD, and a stray byte as itself.
static u32
NextCodepoint(const char **text)
{
  const u8 *bytes = (const u8 *)*text;
  u32 length = bytes[0] < 0xC0 ? 1 : bytes[0] < 0xE0 ? 2 : bytes[0] < 0xF0 ? 3 : 4;
  u32 codepoint = length == 1 ? bytes[0] : bytes[0] & (0x7Fu >> length);
  u32 index = 1;
  for (; index < length && (bytes[index] & 0xC0) == 0x80; index++) {
    codepoint = codepoint << 6 | (bytes[index] & 0x3Fu);
  }
  *text += index;
  return index == length ? codepoint : 0xFFFD;
}

// the glyph for codepoint, or nullptr when the font lacks it.
static const Glyph *
FindGlyph(u32 codepoint)
{
  if (codepoint >= 'a' && codepoint <= 'z') codepoint -= 'a' - 'A';
  for (u64 index = 0; index < sizeof(glyphs) / sizeof(glyphs[0]); index++) {
    if (glyphs[index].codepoint == codepoint) return &glyphs[index];
  }
  return nullptr;
}

u32
FontTextWidth(const char *text, u32 scale)
{
  u32 count = 0;
  while (*text) {
    NextCodepoint(&text);
    count++;
  }
  return count ? (count * fontAdvance - 1) * scale : 0;
}

void
FontDrawText(Image *image, f32 x, f32 y, const char *text, u32 scale, Color color)
{
  f32 left = x;
  while (*text) {
    const Glyph *glyph = FindGlyph(NextCodepoint(&text));
    for (u32 row = 0; glyph && row < fontHeight; row++) {
      for (u32 column = 0; column < 5; column++) {
        if (!(glyph->rows[row] >> (4 - column) & 1)) continue;
        ImageFillRectangle(
          image,
          left + (f32)(column * scale),
          y + (f32)(row * scale),
          (f32)scale,
          (f32)scale,
          color
        );
      }
    }
    left += (f32)(fontAdvance * scale);
  }
}
